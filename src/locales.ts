const numbers = {
  es: new Intl.NumberFormat('es-ES'),
  en: new Intl.NumberFormat('en-US'),
}

export function translate(language: Language, text: string, values?: Values) {
  const message = language === 'en' && Object.hasOwn(english, text) ? english[text] : text
  return values ? message.replace(/\{(\w+)\}/g, (placeholder, key: string) => {
    const value = values[key]
    return typeof value === 'number' ? numbers[language].format(value) : value ?? placeholder
  }) : message
}

export function translateDetail(language: Language, text: string) {
  if (language === 'es') return text
  const http = /^No se pudo cargar el motor Rust \(HTTP (\d+)\)\.$/.exec(text)
  if (http) return translate(language, 'No se pudo cargar el motor Rust (HTTP {status}).', { status: http[1] })
  const container = /^Versión de contenedor (\d+) fuera del rango admitido \(([^)]+)\)\.$/.exec(text)
  if (container) return translate(language, 'Versión de contenedor {version} fuera del rango admitido ({range}).',
    { version: container[1], range: container[2] })
  const catalog = /^(.*) debe contener una lista de objetos\.$/.exec(text)
  if (catalog) return translate(language, '{file} debe contener una lista de objetos.', { file: catalog[1] })
  return translate(language, text)
}

export function localeOf(language: Language) {
  return language === 'es' ? 'es-ES' : 'en-US'
}
